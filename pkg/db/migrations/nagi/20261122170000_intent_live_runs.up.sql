CREATE TABLE intent_decision_runs (
  id uuid PRIMARY KEY,
  bot_id bigint NOT NULL,
  conversation_id uuid NOT NULL,
  job_id bigint NOT NULL CONSTRAINT intent_decision_runs_message_jobs_intent_runs REFERENCES message_jobs(id) ON DELETE CASCADE,
  claim_token uuid NOT NULL,
  state text NOT NULL,
  decision_id bigint CONSTRAINT intent_decision_runs_intent_decisions_intent_run REFERENCES intent_decisions(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL,
  finished_at timestamptz,
  recovery_decision jsonb,
  reply_started boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX intent_decision_runs_decision_id_key ON intent_decision_runs (decision_id);
CREATE UNIQUE INDEX intent_decision_runs_claim ON intent_decision_runs (job_id, claim_token);
CREATE INDEX intent_decision_runs_account ON intent_decision_runs (bot_id, started_at, id);
CREATE INDEX intent_decision_runs_state ON intent_decision_runs (state, started_at);

CREATE TABLE intent_run_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL CONSTRAINT intent_run_events_intent_decision_runs_events REFERENCES intent_decision_runs(id) ON DELETE CASCADE,
  bot_id bigint NOT NULL,
  position bigint NOT NULL,
  sequence bigint NOT NULL,
  kind text NOT NULL,
  data jsonb NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX intent_run_events_sequence ON intent_run_events (run_id, sequence);
CREATE UNIQUE INDEX intent_run_events_position ON intent_run_events (bot_id, position);
CREATE INDEX intent_run_events_time ON intent_run_events (bot_id, created_at, position);

