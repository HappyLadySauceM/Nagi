#!/usr/bin/env bash
# 本地开发环境助手：初始化基础设施、查看数据量、清理开发数据。
# Dev environment helper: initialise the local stack, inspect data and clean it.
#
# 只操作本仓库 docker compose 的固定容器，不读取配置文件里的 DSN，
# 因此不会因为配置指向远端而误删远端数据。
# It only talks to the fixed compose containers and never trusts a configured
# DSN, so a remote database can never be wiped by accident.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

PG_CONTAINER="${PG_CONTAINER:-nagi-postgres}"
CH_CONTAINER="${CH_CONTAINER:-nagi-clickhouse-1}"
REDIS_CONTAINER="${REDIS_CONTAINER:-nagi-redis-1}"
PG_USER="${PG_USER:-nagi}"
PG_DB="${PG_DB:-nagi}"
CH_USER="${CH_USER:-clickhouse}"
CH_PASSWORD="${CLICKHOUSE_PASSWORD:-clickhouse}"
REDIS_PASSWORD="${REDIS_PASSWORD:-nagi-local-redis}"
CONFIG_FILE="${CONFIG_FILE:-configs/config.yaml}"
CONFIG_EXAMPLE="${CONFIG_EXAMPLE:-configs/config-example.yaml}"
BOT_PORT="${BOT_PORT:-5080}"
FRONTEND_PORT="${FRONTEND_PORT:-5173}"
RUN_DIR="${RUN_DIR:-.run}"
BACKEND_PID="$RUN_DIR/backend.pid"
FRONTEND_PID="$RUN_DIR/frontend.pid"
BACKEND_LOG="$RUN_DIR/backend.log"
FRONTEND_LOG="$RUN_DIR/frontend.log"
BACKEND_BIN="bin/nagi"

# 会话类数据：清空后需要重新产生消息。
# Conversation data: cleared first, regenerated by new messages.
BUSINESS_TABLES=(messages message_jobs conversations intent_decisions memories admin_audit_logs)
# 授权与目录缓存：默认保留，只有 --with-scopes 才清。
# Authorization and directory caches: kept unless --with-scopes is given.
SCOPE_TABLES=(scope_policies contacts qq_groups group_members bot_accounts)
# Langfuse 追踪表：只清追踪相关，保留 topics/audit/blob 等非追踪功能。
# Langfuse trace tables only; topics/audit/blob features stay untouched.
CH_TABLES=(events_core events_full observations observations_batch_staging
  observations_pid_tid_sorting traces scores analytics_traces analytics_observations analytics_scores)

if [[ -t 1 ]]; then
  BOLD=$'\033[1m'
  DIM=$'\033[2m'
  RED=$'\033[31m'
  YELLOW=$'\033[33m'
  NC=$'\033[0m'
else
  BOLD='' DIM='' RED='' YELLOW='' NC=''
fi

log() { printf '%s[dev-env]%s %s\n' "$BOLD" "$NC" "$*"; }
warn() { printf '%s[warn]%s %s\n' "$YELLOW" "$NC" "$*" >&2; }
die() {
  printf '%s[error]%s %s\n' "$RED" "$NC" "$1" >&2
  exit "${2:-1}"
}

usage() {
  cat <<'EOF'
用法 / Usage:
  scripts/dev-env.sh init                    启动 compose 并在缺失时生成 configs/config.yaml
  scripts/dev-env.sh run                     后台启动后端与前端（compose 未启动时自动拉起）
  scripts/dev-env.sh exit                    停止后端与前端（别名 stop）
  scripts/dev-env.sh status                  查看业务库、任务、追踪与进程
  scripts/dev-env.sh clean [options]         清理开发数据（默认 dry-run）

clean 选项 / clean options:
  --yes              真正执行清理；不加时只打印计划
  --with-scopes      额外清空 scope_policies 与目录缓存，回到默认拒绝状态
  --reset-volumes    docker compose down -v 后重建（会销毁 Langfuse 登录与 API Key）
  --force            先停止后端与前端，清理完成后自动重启
  -h, --help         显示本帮助

默认清理 / Default clean:
  PG(nagi): messages message_jobs conversations intent_decisions memories admin_audit_logs
  ClickHouse: events_core events_full observations* traces scores analytics_*
  Redis:      bull:*ingestion* 队列
默认保留 / Kept:
  scope_policies、bot_accounts、目录缓存、schema_migrations、Langfuse 登录与 API Key
EOF
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "缺少命令：$1"
}

container_running() {
  [[ "$(docker inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" == "true" ]]
}

require_containers() {
  require_cmd docker
  local name
  for name in "$PG_CONTAINER" "$CH_CONTAINER" "$REDIS_CONTAINER"; do
    container_running "$name" || die "容器 $name 未运行；先执行 scripts/dev-env.sh init" 3
  done
}

pg_query() {
  docker exec "$PG_CONTAINER" psql -U "$PG_USER" -d "$PG_DB" -tAc "$1"
}

table_exists() {
  [[ "$(pg_query "SELECT to_regclass('public.$1') IS NOT NULL")" == "t" ]]
}

ch_query() {
  docker exec "$CH_CONTAINER" clickhouse-client --user "$CH_USER" --password "$CH_PASSWORD" -q "$1"
}

redis_cli() {
  docker exec "$REDIS_CONTAINER" redis-cli -a "$REDIS_PASSWORD" --no-auth-warning "$@"
}

# listener_line prints the first ss line of one port; the output is captured
# first so `pipefail` never turns an early grep exit into a false "free".
# listener_line 输出单个端口的首条 ss 行；先捕获输出，
# 避免 pipefail 把 grep 提前退出误判成“端口空闲”。
listener_line() {
  local port="$1" with_pid="${2:-0}" out line
  if ((with_pid)); then
    out="$(ss -ltnp 2>/dev/null)"
  else
    out="$(ss -ltn 2>/dev/null)"
  fi
  while IFS= read -r line; do
    if [[ "$line" == *":${port} "* ]]; then
      printf '%s\n' "$line"
      return 0
    fi
  done <<<"$out"
  return 1
}

bot_listener() {
  listener_line "$BOT_PORT" 1 || true
}

frontend_listener() {
  listener_line "$FRONTEND_PORT" 1 || true
}

port_busy() {
  listener_line "$1" >/dev/null
}

pid_alive() {
  [[ -f "$1" ]] && kill -0 "$(cat "$1" 2>/dev/null)" 2>/dev/null
}

ensure_run_dir() {
  mkdir -p "$RUN_DIR"
}

wait_http() {
  local url="$1" tries="${2:-20}" i
  for ((i = 0; i < tries; i++)); do
    if curl -fsS -o /dev/null "$url" 2>/dev/null; then
      return 0
    fi
    sleep 1
  done
  return 1
}

wait_port() {
  local port="$1" tries="${2:-30}" i
  for ((i = 0; i < tries; i++)); do
    port_busy "$port" && return 0
    sleep 1
  done
  return 1
}

build_backend_if_needed() {
  local need=0
  if [[ ! -x "$BACKEND_BIN" ]]; then
    need=1
  elif [[ -n "$(find cmd internal pkg migrations go.mod -newer "$BACKEND_BIN" -print -quit 2>/dev/null)" ]]; then
    need=1
  fi
  if ((need)); then
    log "构建后端二进制…"
    go build -o "$BACKEND_BIN" ./cmd
  fi
}

start_backend() {
  if pid_alive "$BACKEND_PID"; then
    log "后端已在运行（PID $(cat "$BACKEND_PID")）"
    return 0
  fi
  if port_busy "$BOT_PORT"; then
    warn "端口 $BOT_PORT 已被其它进程占用（$(bot_listener)）；先执行 just exit"
    return 1
  fi
  ensure_run_dir
  build_backend_if_needed
  setsid nohup "$BACKEND_BIN" --config "$CONFIG_FILE" >>"$BACKEND_LOG" 2>&1 &
  echo $! >"$BACKEND_PID"
  if ! wait_http "http://127.0.0.1:${BOT_PORT}/livez" 30; then
    # 启动慢于预期时再确认一次，避免把已就绪的进程判成失败。
    # Confirm once more so a slow-but-ready process is not reported as failed.
    wait_http "http://127.0.0.1:${BOT_PORT}/livez" 15 || {
      warn "后端 45 秒内未就绪，见 $BACKEND_LOG"
      return 1
    }
  fi
  log "后端已启动 http://127.0.0.1:${BOT_PORT}（PID $(cat "$BACKEND_PID")，日志 $BACKEND_LOG）"
}

start_frontend() {
  if pid_alive "$FRONTEND_PID"; then
    log "前端已在运行（PID $(cat "$FRONTEND_PID")）"
    return 0
  fi
  if port_busy "$FRONTEND_PORT"; then
    warn "端口 $FRONTEND_PORT 已被其它进程占用（$(frontend_listener)）；先执行 just exit"
    return 1
  fi
  [[ -d web/node_modules ]] || die "web/node_modules 缺失；先执行 (cd web && pnpm install)" 3
  command -v pnpm >/dev/null 2>&1 || die "缺少 pnpm（web/pnpm-lock.yaml）" 3
  ensure_run_dir
  (
    cd web
    setsid nohup pnpm dev >>"../$FRONTEND_LOG" 2>&1 &
    echo $! >"../$FRONTEND_PID"
  )
  if ! wait_port "$FRONTEND_PORT" 60; then
    port_busy "$FRONTEND_PORT" || {
      warn "前端 60 秒内未就绪，见 $FRONTEND_LOG"
      return 1
    }
  fi
  log "前端已启动 http://127.0.0.1:${FRONTEND_PORT}（PID $(cat "$FRONTEND_PID")，日志 $FRONTEND_LOG）"
}

stop_pidfile() {
  local name="$1" file="$2" pid
  [[ -f "$file" ]] || return 1
  pid="$(cat "$file" 2>/dev/null || true)"
  if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
    kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
    local i
    for i in $(seq 1 20); do
      kill -0 "$pid" 2>/dev/null || break
      sleep 0.25
    done
    if kill -0 "$pid" 2>/dev/null; then
      kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null || true
    fi
    log "已停止${name}（PID $pid）"
  else
    log "${name}的 PID 文件已过期（${pid:-空}）"
  fi
  rm -f "$file"
  return 0
}

kill_by_port() {
  local port="$1" pattern="$2" line pid cmd
  line="$(listener_line "$port" 1 || true)"
  [[ -n "$line" ]] || return 0
  pid="$(sed -n 's/.*pid=\([0-9]*\).*/\1/p' <<<"$line")"
  if [[ -z "$pid" ]]; then
    warn "端口 $port 被无权限查看的进程占用，跳过"
    return 0
  fi
  cmd="$(tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null || true)"
  case "$cmd" in
    *"$pattern"*)
      kill -TERM "$pid" 2>/dev/null || true
      log "已停止占用 $port 的进程（PID $pid）"
      ;;
    *)
      warn "端口 $port 被其它进程占用（PID $pid），未处理：$cmd"
      ;;
  esac
}

ensure_stack() {
  require_cmd docker
  log "确认 compose 服务…"
  docker compose up -d
  local ready=0 i
  for i in $(seq 1 60); do
    if docker exec "$PG_CONTAINER" pg_isready -U "$PG_USER" -d "$PG_DB" >/dev/null 2>&1; then
      ready=1
      break
    fi
    sleep 1
  done
  ((ready == 1)) || die "PostgreSQL 60 秒内未就绪" 3
}

cmd_status() {
  if container_running "$PG_CONTAINER"; then
    printf '%sPostgreSQL (%s/%s)%s\n' "$BOLD" "$PG_CONTAINER" "$PG_DB" "$NC"
    local t count
    for t in "${BUSINESS_TABLES[@]}" "${SCOPE_TABLES[@]}"; do
      if table_exists "$t"; then
        count="$(pg_query "SELECT count(*) FROM $t")"
        printf '  %-22s %s\n' "$t" "$count"
      fi
    done
    if table_exists message_jobs; then
      printf '  %-22s %s\n' "jobs by status" "$(pg_query "SELECT coalesce(string_agg(status || '=' || n, ' '), '-') FROM (SELECT status, count(*) AS n FROM message_jobs GROUP BY 1 ORDER BY 1) s")"
    fi
  else
    warn "PostgreSQL 容器未运行"
  fi

  if container_running "$CH_CONTAINER"; then
    printf '%sClickHouse traces%s\n' "$BOLD" "$NC"
    local t chcount
    for t in "${CH_TABLES[@]}"; do
      if [[ "$(ch_query "EXISTS TABLE $t")" == "1" ]]; then
        chcount="$(ch_query "SELECT count() FROM $t")"
        printf '  %-28s %s\n' "$t" "$chcount"
      fi
    done
  else
    warn "ClickHouse 容器未运行"
  fi

  local listener
  listener="$(bot_listener)"
  if [[ -n "$listener" ]]; then
    printf '%sBot%s\n  %s\n' "$BOLD" "$NC" "$listener"
  else
    printf '%sBot%s\n  未在 %s 端口运行\n' "$BOLD" "$NC" "$BOT_PORT"
  fi
}

generate_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

prepare_config() {
  if [[ -f "$CONFIG_FILE" ]]; then
    log "配置已存在，保持不变：$CONFIG_FILE"
    return 0
  fi
  [[ -f "$CONFIG_EXAMPLE" ]] || die "缺少示例配置：$CONFIG_EXAMPLE"
  cp "$CONFIG_EXAMPLE" "$CONFIG_FILE"
  local secret
  secret="$(generate_secret)"
  # 只改四行的值，保留示例里的其余内容与注释。
  # Only four values change; the rest of the example stays as written.
  sed -i -E "s|^(  user-id-secret: ).*|\1\"$secret\"|" "$CONFIG_FILE"
  sed -i -E "s|^(  environment: ).*|\1\"local\"|" "$CONFIG_FILE"
  sed -i -E "s|^(  export-raw-content: )[a-z]+|\1true|" "$CONFIG_FILE"
  sed -i -E "s|^(  raw-identifiers: )[a-z]+|\1true|" "$CONFIG_FILE"
  if ! grep -q "user-id-secret: \"$secret\"" "$CONFIG_FILE"; then
    rm -f "$CONFIG_FILE"
    die "写入 user-id-secret 失败，已删除半成品配置"
  fi
  log "已生成 $CONFIG_FILE（随机假名密钥；正文与原始 QQ 导出仅限本地）"
}

cmd_init() {
  require_cmd docker
  log "启动 compose 服务…"
  docker compose up -d

  log "等待 PostgreSQL 就绪…"
  local ready=0 i
  for i in $(seq 1 60); do
    if docker exec "$PG_CONTAINER" pg_isready -U "$PG_USER" -d "$PG_DB" >/dev/null 2>&1; then
      ready=1
      break
    fi
    sleep 1
  done
  ((ready == 1)) || die "PostgreSQL 60 秒内未就绪" 3

  prepare_config
  docker compose ps

  cat <<EOF

${BOLD}下一步 / Next steps${NC}
  1. 启动机器人（首次启动自动应用迁移）: just run
  2. 开启一个作用域（默认拒绝，需显式授权；多账号时带 bot_id）:
     curl -X PUT "http://127.0.0.1:${BOT_PORT}/api/v1/scopes/group/<群号>" \\
       -H 'Content-Type: application/json' \\
       -d '{"enabled":true,"reply_mode":"intent_based","store_messages":true,"allow_history_read":true,"min_reply_interval_ms":3000,"max_replies_per_hour":30,"retention_days":30}'
  3. Langfuse: http://127.0.0.1:3010  账号 admin@nagi.local / nagi-local-2026
  4. 清理开发数据: scripts/dev-env.sh clean --yes
EOF
}

print_clean_plan() {
  local with_scopes="$1" t
  printf '%s将清理 / will clean%s\n' "$BOLD" "$NC"
  printf '  PG(%s): %s\n' "$PG_DB" "${BUSINESS_TABLES[*]}"
  ((${with_scopes:-0})) && printf '  PG(%s) 额外: %s\n' "$PG_DB" "${SCOPE_TABLES[*]}"
  printf '  ClickHouse: %s\n' "${CH_TABLES[*]}"
  printf '  Redis: bull:*ingestion*\n'
  printf '%s保留 / kept%s\n' "$BOLD" "$NC"
  if ((${with_scopes:-0})); then
    printf '  schema_migrations、Langfuse 登录与 API Key\n'
  else
    printf '  %s、schema_migrations、Langfuse 登录与 API Key\n' "${SCOPE_TABLES[*]}"
  fi
}

truncate_business() {
  local with_scopes="$1" t list=""
  local tables=("${BUSINESS_TABLES[@]}")
  ((${with_scopes:-0})) && tables+=("${SCOPE_TABLES[@]}")
  for t in "${tables[@]}"; do
    list+="'$t',"
  done
  list="${list%,}"
  local sql
  sql="SET client_min_messages TO warning;
  DO \$do\$ DECLARE t text; BEGIN
    FOREACH t IN ARRAY ARRAY[${list}] LOOP
      IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name=t) THEN
        EXECUTE format('TRUNCATE TABLE %I RESTART IDENTITY CASCADE', t);
      END IF;
    END LOOP;
  END \$do\$;"
  docker exec "$PG_CONTAINER" psql -U "$PG_USER" -d "$PG_DB" -v ON_ERROR_STOP=1 -q -c "$sql"
  log "已清空 PostgreSQL 业务表"
}

truncate_clickhouse() {
  local t engine
  for t in "${CH_TABLES[@]}"; do
    # 视图（analytics_* 等）不支持 TRUNCATE，只清真实表。
    # Views (analytics_*) cannot be truncated; only real tables are cleared.
    engine="$(ch_query "SELECT engine FROM system.tables WHERE database='default' AND name='$t'")"
    [[ -z "$engine" ]] && continue
    case "$engine" in
      *View*) continue ;;
    esac
    ch_query "TRUNCATE TABLE $t"
  done
  log "已清空 ClickHouse 追踪表"
}

clear_redis_queues() {
  local keys
  keys="$(redis_cli --scan --pattern 'bull:*ingestion*' || true)"
  if [[ -z "$keys" ]]; then
    log "Redis 无待清理的 ingestion 队列"
    return 0
  fi
  # shellcheck disable=SC2086
  printf '%s\n' "$keys" | xargs -r -n 50 docker exec "$REDIS_CONTAINER" \
    redis-cli -a "$REDIS_PASSWORD" --no-auth-warning DEL >/dev/null
  log "已清理 Redis ingestion 队列"
}

cmd_run() {
  require_cmd go
  require_cmd curl
  ensure_stack
  start_backend || die "后端启动失败" 3
  start_frontend || die "前端启动失败" 3
  log "后端 http://127.0.0.1:${BOT_PORT}  前端 http://127.0.0.1:${FRONTEND_PORT}  停止：just exit"
}

cmd_exit() {
  stop_pidfile "后端" "$BACKEND_PID" || true
  stop_pidfile "前端" "$FRONTEND_PID" || true
  # PID 文件缺失时按端口兜底，但只处理本仓库启动的进程。
  # Fall back to the ports, but only for processes started from this repo.
  kill_by_port "$BOT_PORT" "bin/nagi"
  kill_by_port "$FRONTEND_PORT" "/web/"
  local i
  for i in $(seq 1 20); do
    port_busy "$BOT_PORT" || port_busy "$FRONTEND_PORT" || break
    sleep 0.25
  done
  if port_busy "$BOT_PORT" || port_busy "$FRONTEND_PORT"; then
    warn "仍有进程占用端口：$(bot_listener) $(frontend_listener)"
    return 1
  fi
  log "后端与前端已停止"
}

cmd_clean() {
  local yes=0 with_scopes=0 reset_volumes=0 force=0
  while (($#)); do
    case "$1" in
      --yes) yes=1 ;;
      --with-scopes) with_scopes=1 ;;
      --reset-volumes) reset_volumes=1 ;;
      --force) force=1 ;;
      -h | --help) usage; exit 0 ;;
      *) die "未知参数：$1" 2 ;;
    esac
    shift
  done

  if ((reset_volumes)); then
    ((yes)) || {
      print_clean_plan "$with_scopes"
      printf '  %s--reset-volumes: docker compose down -v 并重建所有卷%s\n' "$YELLOW" "$NC"
      log "dry-run：未执行；确认后加 --yes"
      return 0
    }
    warn "将销毁所有 compose 卷：业务库、Langfuse 登录、API Key 与追踪数据都会重建"
    ((force)) && cmd_exit
    docker compose down -v
    docker compose up -d
    if ((force)); then
      cmd_run
    else
      log "已重建；配置保持不变，迁移会在机器人首次启动时应用"
    fi
    return 0
  fi

  print_clean_plan "$with_scopes"
  if ((!yes)); then
    log "dry-run：未修改任何数据；确认后加 --yes 执行"
    return 0
  fi

  if ((force)); then
    cmd_exit
  else
    local listener
    listener="$(bot_listener)"
    if [[ -n "$listener" ]]; then
      die "机器人在 ${BOT_PORT} 端口运行（$listener）；请先 just exit，或加 --force 自动停服并重启" 3
    fi
  fi

  require_containers

  truncate_business "$with_scopes"
  truncate_clickhouse
  clear_redis_queues
  if ((force)); then
    log "清理完成，重新启动后端与前端…"
    cmd_run
  fi
  log "清理完成，当前状态："
  cmd_status
}

main() {
  (($#)) || {
    usage
    exit 2
  }
  local command="$1"
  shift
  case "$command" in
    init) cmd_init "$@" ;;
    run) cmd_run "$@" ;;
    exit | stop) cmd_exit "$@" ;;
    status) cmd_status "$@" ;;
    clean) cmd_clean "$@" ;;
    -h | --help | help) usage ;;
    *) die "未知子命令：$command" 2 ;;
  esac
}

main "$@"
